# Various Dataset object configurations for use with training and inference
# All take a keyfile specifying one or more labeled PS4G count matrices in npy format

from transformers.data.data_collator import InputDataClass
from transformers.data.data_collator import default_data_collator
from torch.utils.data import Dataset
import numpy as np
import torch
import pandas as pd
from scipy.stats import binom
import random


class BaseSegmentationDataset(Dataset):
    """ The "default" dataset object. It can pull a given window from the .npy read count files
        and parses the crossover points from the included labels.
        Parameters:
            keyfile -- tab-delimited table of .npy files to be used. Generated by generate_keyfile.py
            input_len -- length of the context window
            num_parents -- number of parents used in the PS4G file
            step_size -- offset for each input window. e.g. the start of dataset[x+1] is <step_size> after the start of dataset[x]
            include_index -- include the file and position index in the returned dictionary for __get_item__()
            end_token -- int, the token index to use as the special end token. Defaults to input_len + 1
            include_end_token_rate -- proportion of end tokens that will be unmasked in the dataset. Used to downsample end tokens
            preload -- if true, load all data into memory. Use this if running inference on a single or a few samples, to improve speed.
    """

    def __init__(self, keyfile, input_len=256, num_parents=24, step_size=128, windows=None, include_index=False,
                 end_token=None, include_end_token_rate=1.0, preload=False, distribute_label_density=False):
        self.keyfile = pd.read_csv(keyfile, sep="\t")
        self.input_len = input_len
        self.num_parents = num_parents
        self.step_size = step_size
        self.distribute_label_density = distribute_label_density

        if distribute_label_density:
            self.format_labels = self.distribute_labels
        else:
            self.format_labels = self.int_labels

        if windows is not None:
            self.windows = list(pd.read_csv(windows, sep="\t").itertuples(index=False))
        else:
            self.windows = self.__generate_windows__()
        self.include_index = include_index

        self.n_windows = len(self.windows)

        if end_token is None:
            self.end_token = self.input_len + 1
        else:
            self.end_token = end_token

        self.include_end_token_rate = include_end_token_rate

        self.preload = preload

        if preload:
            self.matrices = [np.load(self.keyfile["path"].iloc[idx], allow_pickle=True) for idx in
                             range(len(self.keyfile))]

    def __generate_windows__(self):
        """Stores all valid training windows as a list of tuples, for random access by get_item
            Tuples are formatted as (file index, window step index), with file index taken from
            the order presented in the keyfile.
            Multiple window step index by step size to get the index of the first position in the
            window from the .npy files.
        """
        windows = []  # file idx, window step idx

        for idx in range(len(self.keyfile)):
            filelen = self.keyfile.iloc[idx]["length"]
            num_windows = (filelen - self.input_len) // self.step_size
            windows.extend([(idx, idy) for idy in range(num_windows)])

        return windows

    def __len__(self):
        return self.n_windows

    def dist(self, idx):
        """Returns the binomial distribution of a label for distribute_label_density=True"""

        x = torch.zeros((self.input_len))
        # TODO: parameterize
        midpoint = 32 // 2

        for idy in range(32):
            # special tokens (i.e. <END>) do not get distributed density
            if 0 <= idx + idy - midpoint < self.input_len:
                x[idx + idy - midpoint] = binom.pmf(idy, 32, 0.5)

        return x

    def distribute_labels(self, junctions):
        """Configure labels as binomial distributions.
            Returns:
                input_ids: input token IDs
                labels_binom: labels formatted as distributions
                mask: attention mask
                int_labels: labels formatted as token IDs. Useful for quickly identifying the correct answer
        """

        input_ids, int_labels, mask = self.__junctions_to_io__(junctions)
        labels_binom = np.array([self.dist(idx) for idx in junctions])

        # add special tokens and end token
        if labels_binom.shape[0] == 0:  # no crossovers

            labels_binom = np.zeros((1, self.input_len + 3))
        else:  # yes crossovers

            labels_binom = np.concatenate((labels_binom, np.zeros((labels_binom.shape[0], 3))), axis=1)
            labels_binom = np.concatenate((labels_binom, np.zeros((1, labels_binom.shape[1]))), axis=0)

        # add end token label (no smoothing)
        labels_binom[labels_binom.shape[0] - 1, self.input_len + 1] = 1

        return input_ids, labels_binom, mask, int_labels

    def int_labels(self, junctions):
        """Configure labels as integer token IDs.
            Returns:
                input_ids: input token IDs
                labels: labels formatted as token IDs
                mask: attention mask
                int_labels: labels formatted as token IDs

            labels are returned twice to keep format consistent with distribute_labels()
        """
        input_ids, labels, mask = self.__junctions_to_io__(junctions)
        # we do this to keep the format consistent with distributed labels
        return input_ids, labels, mask, labels

    def __bins_to_idx__(self, labels_binned):
        """Converts per-position labels from .npy files to a list of crossover points"""
        return [idx + 1 for idx in range(labels_binned.shape[0] - 1) if labels_binned[idx] != labels_binned[idx + 1]]

    def __read_window_data__(self, file_idx, pos_idx):
        """Read and format data from input files for a specific context window"""
        # convert to position start and end
        pos_start = pos_idx * self.step_size
        pos_end = pos_start + self.input_len

        if self.preload:
            ip = self.matrices[file_idx][pos_start:pos_end]
        else:
            # grab segment from mmaped numpy
            ip = np.load(self.keyfile["path"].iloc[file_idx], allow_pickle=True, mmap_mode='r')[pos_start:pos_end]

        # separate labels and generate junctions aka crossover points
        labels_binned = ip[:, self.num_parents]
        junctions = self.__bins_to_idx__(labels_binned)

        matrix = ip[:, 0:self.num_parents]

        return matrix, junctions

    def __junctions_to_io__(self, junctions):
        """Format crossover points for sequence decoders - with input_ids and labels offset by one,
        plus attention mask.
        """
        # We've got labels and decoder input id's separately here, even though they should just be
        # shifted versions of one another. This was part of debugging that I did because
        # I think the default shifting function built into the model isn't working right
        # for our needs. Specifying both overrides the default though.
        input_ids = np.concatenate(([self.input_len + 2], junctions))
        labels = np.concatenate((junctions, [self.end_token]))

        mask = np.ones(len(junctions) + 1)

        if random.random() > self.include_end_token_rate:
            mask[-1] = 0

        return input_ids, labels, mask

    def __getitem__(self, idx):
        # retrieve window index from list
        file_idx, pos_idx = self.windows[idx]

        matrix, junctions = self.__read_window_data__(file_idx, pos_idx)

        # normalize the matrix  (z-score)
        # TODO: try different normalization methods
        mean = np.mean(matrix)
        sd = np.std(matrix)
        window = (matrix - mean) / sd

        # format input ids and labels
        input_ids, labels, mask, int_labels = self.format_labels(junctions)

        # Note: we are relying on the data collator to handle padding, so labels do not have a fixed length
        return_dict = {
            'encoder_hidden_states': torch.tensor(window, dtype=torch.float),  # (input_len, num_parents)
            'labels': torch.tensor(labels),  # (N - variable depending on the number of crossovers in a window)
            'attention_mask': mask,  # (N)
            'input_ids': torch.tensor(input_ids),  # (N)
            'int_labels': torch.tensor(int_labels)
        }

        if self.include_index:
            return_dict["file_idx"] = file_idx
            return_dict["pos_idx"] = pos_idx
            return_dict["idx"] = idx

        return return_dict

    def collate(self, features: list[InputDataClass]):
        """Custom data collator function to handle the variable label length in this dataset."""
        # loss calculations will ignore this token
        padding_token = -100
        input_padding_token = self.input_len

        # pad label features to the length of the longest
        # right-padded for training
        longest_seq = np.max([feat["labels"].shape[0] for feat in features])

        for feat in features:
            if feat["labels"].shape[0] < longest_seq:
                pad_len = longest_seq - feat["labels"].shape[0]

                if self.distribute_label_density:
                    labels_dim = (pad_len, *feat["labels"].shape[1:])
                    feat["labels"] = np.concatenate((feat["labels"], np.full(labels_dim, 0)))
                else:
                    feat["labels"] = np.concatenate((feat["labels"], [padding_token] * pad_len))
                feat["input_ids"] = np.concatenate((feat["input_ids"], [input_padding_token] * pad_len))
                feat["attention_mask"] = np.concatenate((feat["attention_mask"], np.zeros(pad_len)))

                if "int_labels" in feat.keys():
                    feat["int_labels"] = np.concatenate((feat["int_labels"], [padding_token] * pad_len))

            if "int_labels" in feat.keys():
                feat["int_labels"] = torch.tensor(feat["int_labels"], dtype=torch.int64).clone()
            feat["input_ids"] = torch.tensor(feat["input_ids"], dtype=torch.int64).clone()
            feat["labels"] = torch.tensor(feat["labels"]).clone()

        # pass padded tokens to default collator
        batch = default_data_collator(features)

        return batch


class VisionSegmentationDataset(BaseSegmentationDataset):
    """Inherets from BaseSegmentationDataset, but formats the input matrix as an image with RGB channels.
        Parameters:
            image_size -- Side length of the square image to be used as input. Long context windows will be
                wrapped to fit the square dimensions
            split_norm_levels -- if true, sets RGB channels to local, chromosome-wide, and genome-wide normalization.
                If false (default), all channels will be locally normalized, resulting in a greyscale "image"
            distribute_label_density -- If true, labels are represented as binomial probability densities instead of
                categorical labels. This results in slower training, but allows for some "fuzziness" in loss function
                and model accuracy, since loss can be conditioned on the distance to the nearest labeled crossover.
    """

    def __init__(self, keyfile, image_size=384, num_parents=24, step_size=1536, windows=None, split_norm_levels=False,
                 include_index=False, preload=False, distribute_label_density=False):
        window_size = (image_size * image_size) // num_parents
        super().__init__(keyfile, window_size, num_parents, step_size, windows, include_index, preload,
                         distribute_label_density)

        # use variables for these functions to avoid conditionals in training
        if split_norm_levels:
            self.norm_func = self.normalize_global
        else:
            self.norm_func = self.normalize_local

    def normalize_local(self, matrix, file_idx):
        """Normalize the input matrix.
            Local normalization is set so that the mean value is 0.5 and the standard deviation is 0.5
            across the input matrix.
            All three channels (RGB) contain the same locally normalized values
        """
        mean = np.mean(matrix)
        sd = np.std(matrix)
        matrix_r = (matrix - mean) / sd
        matrix_r = matrix_r * 0.5 + 0.5
        return np.stack((matrix_r, matrix_r, matrix_r), axis=0)

    def normalize_global(self, matrix, file_idx):
        """Normalize the input matrix.
            Normalization is set so that the mean value is 0.5 and the standard deviation is 0.5
            R channel normalizes relative to the values within the input matrix
            G channel normalizes relative to the values within the chromosome
            B channel normalizes relative to the values across all chromosomes for the sample
            The keyfile must include colums for chromosomal and global means and standard deviations.
        """
        mean = np.mean(matrix)
        sd = np.std(matrix)
        matrix_r = (matrix - mean) / sd
        matrix_r = matrix_r * 0.5 + 0.5

        # pull precalculated chrom/global mean and sd from the keyfile
        matrix_g = (matrix - self.keyfile.iloc[file_idx]["chrom_mean"]) / self.keyfile.iloc[file_idx]["chrom_stdev"]
        matrix_g = matrix_g * 0.5 + 0.5

        matrix_b = (matrix - self.keyfile.iloc[file_idx]["global_mean"]) / self.keyfile.iloc[file_idx][
            "global_stdev"]
        matrix_b = matrix_b * 0.5 + 0.5

        return np.stack((matrix_r, matrix_g, matrix_b), axis=0)

    def __getitem__(self, idx):
        # retrieve window index from list
        file_idx, pos_idx = self.windows[idx]

        # load data
        matrix, junctions = self.__read_window_data__(file_idx, pos_idx)
        matrix = np.hstack(np.split(matrix, self.input_len // self.input_len))

        # normalize the matrix according to ViT's requirements (mean 0.5 std 0.5)
        window = self.norm_func(matrix, file_idx)

        # format the labels
        input_ids, labels, mask, int_labels = self.format_labels(junctions)

        return_dict = {
            'pixel_values': torch.tensor(window, dtype=torch.float),  # (3, image_size, image_size)
            "labels": torch.tensor(labels),
            # (N) or (N, input_len + 3), for integer or distributive labeling, respectively
            "int_labels": torch.tensor(int_labels),  # (N - variable)
            'decoder_attention_mask': mask,  # (N)
            'decoder_input_ids': torch.tensor(input_ids)  # (N)
        }

        if self.include_index:
            return_dict["file_idx"] = file_idx
            return_dict["pos_idx"] = pos_idx
            return_dict["idx"] = idx

        return return_dict

    def collate(self, features: list[InputDataClass]):
        """Custom data collator to handle variable label lengths for this dataset"""
        # loss calculations will ignore this token
        padding_token = -100
        input_padding_token = self.input_len

        # pad label features to the length of the longest
        # right-padded for training
        longest_seq = np.max([feat["labels"].shape[0] for feat in features])

        for feat in features:
            if feat["labels"].shape[0] < longest_seq:
                pad_len = longest_seq - feat["labels"].shape[0]
                labels_dim = (pad_len, *feat["labels"].shape[1:])

                if self.distribute_label_density:
                    labels_dim = (pad_len, *feat["labels"].shape[1:])
                    feat["labels"] = np.concatenate((feat["labels"], np.full(labels_dim, 0)))
                else:
                    feat["labels"] = np.concatenate((feat["labels"], [padding_token] * pad_len))

                if "int_labels" in feat.keys():
                    feat["int_labels"] = np.concatenate((feat["int_labels"], [padding_token] * pad_len))
                feat["decoder_input_ids"] = np.concatenate((feat["decoder_input_ids"], [input_padding_token] * pad_len))
                feat["decoder_attention_mask"] = np.concatenate((feat["decoder_attention_mask"], np.zeros(pad_len)))

            if "int_labels" in feat.keys():
                feat["int_labels"] = torch.tensor(feat["int_labels"], dtype=torch.int64).clone()
            feat["decoder_input_ids"] = torch.tensor(feat["decoder_input_ids"], dtype=torch.int64).clone()
            feat["labels"] = torch.tensor(feat["labels"]).clone()

        # pass padded tokens to default collator
        batch = default_data_collator(features)

        # Vision to sequence model was crashing when trying to return a dictionary, so we disable it
        batch["return_dict"] = False

        return batch


class CategoricalDataset(BaseSegmentationDataset):
    """Inherets from BaseSegmentationDataset.
        Instead of labeling where crossovers occur, this class gives a single binary label indication
        whether a window has a crossover or not. Multiple crossovers within a window are treated the same as
        a single crossover.
    """

    def __init__(self, keyfile, input_len=64, num_parents=24, step_size=16, windows=None, include_index=False,
                 preload=False, padding=0):
        super().__init__(keyfile, input_len, num_parents, step_size, windows, include_index, preload)
        self.padding = padding

    def __getitem__(self, idx):
        # retrieve window index from list
        file_idx, pos_idx = self.windows[idx]

        matrix, junctions = self.__read_window_data__(file_idx, pos_idx)

        # normalize the matrix  (z-score)
        # TODO: try different normalization methods
        mean = np.mean(matrix)
        sd = np.std(matrix)
        window = (matrix - mean) / sd

        # allows us to ignore crossovers at the sides
        junctions = [junc for junc in junctions if self.padding <= junc < (self.input_len - self.padding)]

        if len(junctions) > 0:
            label = 1
        else:
            label = 0

        return_dict = {
            'inputs_embeds': torch.tensor(window, dtype=torch.float),
            "labels": label
        }

        if self.include_index:
            return_dict["file_idx"] = file_idx
            return_dict["pos_idx"] = pos_idx
            return_dict["idx"] = idx

        return return_dict

    def collate(self, features: list[InputDataClass]):
        return default_data_collator(features)


class CategoricalMulticlassDataset(BaseSegmentationDataset):
    """Inherets from BaseSegmentationDataset.
        Instead of labeling where crossovers occur, this class gives a single binary label indication
        whether a window has a crossover or not. Multiple crossovers within a window are treated the same as
        a single crossover.
    """

    def __init__(self, keyfile, input_len=64, num_parents=24, step_size=16, windows=None, include_index=False,
                 preload=False):
        super().__init__(keyfile, input_len, num_parents, step_size, windows, include_index, preload)

    def __getitem__(self, idx):
        # retrieve window index from list
        file_idx, pos_idx = self.windows[idx]

        matrix, junctions = self.__read_window_data__(file_idx, pos_idx)

        # normalize the matrix  (z-score)
        # TODO: try different normalization methods
        mean = np.mean(matrix)
        sd = np.std(matrix)
        window = (matrix - mean) / sd

        start = self.input_len // 4
        end = start * 3

        junctions = [junc for junc in junctions if start <= junc < end]

        if len(junctions) > 0:
            label = junctions[0] - start
        else:
            label = end - start

        return_dict = {
            'inputs_embeds': torch.tensor(window, dtype=torch.float),
            "labels": label
        }

        if self.include_index:
            return_dict["file_idx"] = file_idx
            return_dict["pos_idx"] = pos_idx
            return_dict["idx"] = idx

        return return_dict

    def collate(self, features: list[InputDataClass]):
        return default_data_collator(features)


class CategoricalVisionSegmentationDataset(VisionSegmentationDataset):
    """Inherets from VisionSegmentationDataset, but returns a binary label
     for whether a crossover occurs, in the same manner as CategoricalDataset.
     """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

    def __getitem__(self, idx):
        # retrieve window index from list
        file_idx, pos_idx = self.windows[idx]

        # load data
        matrix, junctions = self.__read_window_data__(file_idx, pos_idx)
        matrix = np.hstack(np.split(matrix, self.input_len // self.input_len))

        # normalize the matrix according to ViT's requirements (mean 0.5 std 0.5)
        window = self.norm_func(matrix, file_idx)

        if len(junctions) > 0:
            label = 1
        else:
            label = 0

        return_dict = {
            'pixel_values': torch.tensor(window, dtype=torch.float),  # (3, image_size, image_size)
            "labels": label,  # (1)
        }

        if self.include_index:
            return_dict["file_idx"] = file_idx
            return_dict["pos_idx"] = pos_idx
            return_dict["idx"] = idx

        return return_dict

    def collate(self, features: list[InputDataClass]):
        return default_data_collator(features)
